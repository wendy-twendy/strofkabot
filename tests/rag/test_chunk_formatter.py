"""Tests for chunk formatting functionality.

These tests verify the chunk formatting for embeddings:
- Header includes channel, time range, participants with nicknames
- Reply indicators show "(reply to X)"
- Messages with no content show [no text]
- Unique chunk IDs are generated
- Formatted text preserves conversation structure
"""

from __future__ import annotations

import datetime
import uuid

from strofkabot.db.message_history import HistoryMessage
from strofkabot.rag.chunking.chunk_formatter import ChunkFormatter, FormattedChunk
from strofkabot.rag.chunking.conversation_grouper import ConversationGroup


class TestFormattedChunk:
    """Tests for FormattedChunk dataclass."""

    def test_creation(self, sample_messages):
        """FormattedChunk should be creatable with required fields."""
        chunk = FormattedChunk(
            chunk_id="test-chunk-id",
            raw_text="Some raw text",
            formatted_text="[Header]\nSome raw text",
            messages=sample_messages[:2],
            metadata={"channel_id": 100},
        )

        assert chunk.chunk_id == "test-chunk-id"
        assert "Some raw text" in chunk.raw_text
        assert chunk.metadata["channel_id"] == 100

    def test_chunk_id_is_valid_uuid(self):
        """Chunk IDs generated by formatter should be valid UUIDs."""
        # This will be tested via the formatter
        chunk = FormattedChunk(
            chunk_id=str(uuid.uuid4()),
            raw_text="",
            formatted_text="",
            messages=[],
            metadata={},
        )

        # Should not raise
        uuid.UUID(chunk.chunk_id)


