class TestFormatMessages:
    """Tests for message formatting within chunks."""

    def test_messages_have_author_prefix(self, sample_messages, sample_nicknames):
        """Each message should start with author name."""
        formatter = ChunkFormatter(nicknames=sample_nicknames)

        group = ConversationGroup(
            channel_id=100,
            channel_name="kanapeja",
            start_time=sample_messages[0].timestamp,
            end_time=sample_messages[0].timestamp,
            messages=[sample_messages[0]],
            participant_ids={sample_messages[0].author_id},
        )

        chunk = formatter.format_for_embedding(group)

        # Message should have author prefix
        assert "Takarak:" in chunk.formatted_text or "Takarak (" in chunk.formatted_text

    def test_reply_indicator_included(self, sample_messages, sample_nicknames):
        """Reply messages should show reply indicator."""
        formatter = ChunkFormatter(nicknames=sample_nicknames)

        # Messages 4-5 are a reply chain
        group = ConversationGroup(
            channel_id=100,
            channel_name="kanapeja",
            start_time=sample_messages[4].timestamp,
            end_time=sample_messages[4].timestamp,
            messages=[sample_messages[4]],  # This is a reply
            participant_ids={sample_messages[4].author_id},
        )

        chunk = formatter.format_for_embedding(group)

        # Should indicate it's a reply
        assert "reply" in chunk.formatted_text.lower() or "→" in chunk.formatted_text

    def test_empty_content_shows_placeholder(self, sample_nicknames):
        """Messages with empty content should show [no text]."""
        formatter = ChunkFormatter(nicknames=sample_nicknames)

        base_time = datetime.datetime(2025, 10, 15, 14, 0, 0, tzinfo=datetime.UTC)
        empty_msg = HistoryMessage(
            id=1,
            channel_id=100,
            channel_name="kanapeja",
            author_id=301411562487545857,
            author_name="Takarak",
            content="",
            timestamp=base_time,
            reply_to_id=None,
            reply_to_author=None,
            reply_to_content=None,
            reactions="[]",
        )

        group = ConversationGroup(
            channel_id=100,
            channel_name="kanapeja",
            start_time=base_time,
            end_time=base_time,
            messages=[empty_msg],
            participant_ids={301411562487545857},
        )

        chunk = formatter.format_for_embedding(group)

        # Should show placeholder for empty content
        assert "[no text]" in chunk.formatted_text or "[empty]" in chunk.formatted_text


